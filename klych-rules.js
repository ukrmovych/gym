function klychLast(s) { return String(s).trim().split(/\s+/).pop(); }
function klychRule(row) {
  const [frame, nomFull, vocFull] = row;
  const male = ["pm", "sm", "lm", "bm"].includes(frame);
  const n = klychLast(nomFull), forms = vocFull.split("|").map(klychLast);
  const ends = e => forms.some(f => f.endsWith(e));
  const base = { n, forms };
  if (KLYCH_SPECIAL[n]) return { ...base, lines: KLYCH_SPECIAL[n] };
  const lc = n.toLowerCase(), R = KLYCH_RULES;
  let r = null; // [правило, чи збігається з правильною формою]
  if (frame === "ln") r = [R.iv, forms[0] === n];
  else if (/[аеєиіїоуюяй']я$/.test(lc)) r = [R.yaVowel, ends("є")];
  else if (/а$/.test(lc)) r = [R.a, /[жчшщ]а$/.test(lc) ? ends("е") : ends("о")];
  else if (/я$/.test(lc)) r = [R.yaCons, ends("е") || ends("ю")];
  else if (/ко$/.test(lc)) r = [R.o, ends("ку")];
  else if (/о$/.test(lc) && male) r = [R.o, ends("е")];
  else if (/[йь]$/.test(lc) && male) r = [R.soft, KLYCH_EXC_CHE.includes(lc) ? ends("че") : ends("ю")];
  else if (!male) r = [R.fem, ends("е")];
  else if (/р$/.test(lc)) r = [R.r, ends("ю") || ends("е")];
  else if (/(ик|ік|ок|лог)$/.test(lc) || (/^[А-ЯІЇЄҐ]/.test(n) && /(ук|юк)$/.test(lc))) r = [R.u, ends("у")];
  else if (/[гкх]$/.test(lc)) r = [R.gkh, ends("же") || ends("че") || ends("ше")];
  else r = [R.hard, /[чшжщ]$/.test(lc) ? ends("у") : ends("е")];
  if (r && r[1]) return { ...base, lines: r[0] };
  return { ...base, lines: [{ r: "запам'ятай окремо", e: `${n} → ${forms.join(" / ")}` }] };
}
// «Оксана → Оксано»: спільний початок звичайний, закінчення — помаранчеве
function klychPair(a, b) {
  let i = 0;
  while (i < a.length && i < b.length && a[i] === b[i]) i++;
  if (i === a.length && i === b.length) return `${a} → ${b}`;
  const e = s => `${s.slice(0, i)}<b class="kr-end">${s.slice(i)}</b>`;
  return `${e(a)} → ${e(b)}`;
}
function klychRuleHtml(k) {
  const esc = s => String(s).replace(/[&<>]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;" }[c]));
  const marks = s => esc(s).replace(/(^|[\s(«,…])(-[а-яіїєґ']+)/gi, '$1<b class="kr-end">$2</b>'); // «-а → -о»
  const exs = s => esc(s).replace(/([А-ЯІЇЄҐа-яіїєґ'’]+) → ([А-ЯІЇЄҐа-яіїєґ'’]+)/g, (m, a, b) => klychPair(a, b));
  const head = k.forms.map(f => klychPair(k.n, f)).join(" / ");
  return `<span class="kr-word">💡 ${head}</span>` + k.lines.map(l =>
    `<span class="kr-line"><span class="kr-r">${marks(l.r)}</span>${l.e ? `<span class="kr-e">${l.e.split(/,\s(?![^()]*\))/).map(x => `<span class="kr-ex">${exs(x)}</span>`).join("")}</span>` : ""}</span>`).join("");
}
